user_Language = input("Enter your Language:")   #Ask user for There Favourite Language.

original = user_Language                        #Original Sentence.
print("Original:",original)                     

upperCase = original.upper()                    #Uppercase Sentence.
print("Uppercase:",upperCase)

lowerCase = original.lower()                    #Lowercase Sentence.
print("Lowercase:",lowerCase)

titleCase = original.title()                    #Titlecase Sentence.
print("Title:", titleCase)

capitalized = original.capitalize()             #Capitalized Sentence.
print("Capitalized:", capitalized)